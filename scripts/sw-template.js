// App-shell service worker. Caches same-origin navigation/static assets so
// the installed app can open offline. Never intercepts /api/* — those calls
// carry no secrets client-side, but their freshness semantics are owned by
// the app's own IndexedDB caching layer, not the browser cache.
//
// This file is a TEMPLATE (scripts/sw-template.js), not what gets served.
// scripts/generate-app-shell.mjs stamps the CACHE_NAME version below with a
// hash of this build's actual asset list, fills in ROUTES from
// config/routes.json, and writes the result to public/sw.js (gitignored,
// regenerated by `npm run build`/`npm run dev`). Baking the version into the
// served script's own source — rather than reading it at runtime — is what
// makes a new deploy's precache genuinely distinct from the previous one: the
// browser detects sw.js's bytes changed, installs a new worker under a new
// cache name, and activate's cleanup below then deletes every cache that
// isn't it.
//
// LIFECYCLE (waiting-worker policy, chunk 3): a new worker installs and then
// WAITS while any page controlled by the old one is open. There is no
// skipWaiting() on install and no clients.claim(), so a page is never moved
// to a worker whose cache doesn't hold the assets it was built from. It
// activates when every old page has closed, or when the user taps Reload on
// the app's "Update available" prompt, which posts SKIP_WAITING to this
// waiting worker only (app/ServiceWorkerRegistration.tsx).

const CACHE_NAME = "parlay-helper-shell-__CACHE_VERSION__";
const ROUTES = __ROUTES__;
const OFFLINE_URL = "/ideas";

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      // predev/postbuild always write a valid manifest before this file is
      // ever served, so a missing or malformed one here is a real problem
      // (a bad deploy, a serving misconfiguration) — let the install fail
      // loudly instead of silently precaching a smaller, possibly-stale
      // fallback list that would quietly undercut the offline guarantee.
      // Fetched and validated before opening any cache, so a failed
      // install leaves no orphaned (even if empty) cache behind.
      const manifestResponse = await fetch("/precache-manifest.json", { cache: "no-store" });
      if (!manifestResponse.ok) {
        throw new Error(`precache-manifest.json fetch failed: ${manifestResponse.status}`);
      }
      const urls = await manifestResponse.json();
      if (!Array.isArray(urls) || urls.length === 0) {
        throw new Error("precache-manifest.json was empty or malformed");
      }
      const cache = await caches.open(CACHE_NAME);
      await cache.addAll(urls);
    })(),
  );
});

self.addEventListener("activate", (event) => {
  // Every other cache is deleted, and assets are never looked up across
  // caches: an old page that somehow outlived its worker reloads instead of
  // mixing versions.
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key)))),
  );
});

self.addEventListener("message", (event) => {
  // Sent only by the "Update available" prompt, and only to the waiting
  // worker; an active worker ignores it.
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/")) return;

  const isNavigation = request.mode === "navigate";

  // An old screen name (/capture, /bucket, /builder) is redirected to its
  // canonical route before any cache or network decision, online or
  // offline, with the query kept. Same map as next.config's 308s. The
  // redirect itself is never cached.
  if (isNavigation && Object.prototype.hasOwnProperty.call(ROUTES.aliases, url.pathname)) {
    event.respondWith(Response.redirect(new URL(ROUTES.aliases[url.pathname] + url.search, url.origin).href, 308));
    return;
  }

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE_NAME);
      try {
        const networkResponse = await fetch(request);
        // A response that followed a redirect (e.g. / -> /ideas) is never
        // stored: served later for a navigation, the browser rejects it.
        if (networkResponse && networkResponse.ok && !networkResponse.redirected) {
          cache.put(request, networkResponse.clone());
        }
        return networkResponse;
      } catch {
        const cached = await cache.match(request);
        if (cached) return cached;
        if (isNavigation) {
          // A screen opened with a query falls back to ITS OWN screen's
          // cached page (the query is read client-side), never to another
          // screen's. Any other path lands on Ideas.
          if (ROUTES.canonical.includes(url.pathname)) {
            const own = await cache.match(url.pathname);
            if (own) return own;
          } else {
            const offlineShell = await cache.match(OFFLINE_URL);
            if (offlineShell) return offlineShell;
          }
        }
        throw new Error("offline and not cached");
      }
    })(),
  );
});
